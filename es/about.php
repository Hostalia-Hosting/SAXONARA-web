                            <h2 class="artist-name">Arnald SAXONARA</h2>
                            <p><b>Me llamo Arnald SAXONARA, soy músico y saxofonista en eventos, bodas y también dando conciertos, a continuación os hago un breve resumen de mi carrera</b></p>
                            <p>Nací en 1990 👶 y empecé mis estudios de música con 7 años, incialmente tocando el <b>piano 🎹</b> y siguiendo la formación reglada de las Escuelas de Música de Linyola y Mollerussa. Con el paso del tiempo, y según fueron evolucionando mis gustos, dejé de un lado el piano para centrarme en el estudio de la <b>música moderna</b>, esta vez como <b>guitarrista 🎸</b> y ya participando de bandas y tocando en directo. Unos años después, ya de adolescente, empecé con el <b>saxofón 🎷</b> como segundo instrumento, pero rápidamente paso a tomar todo el protagonismo, relegando la guitarra a un segundo plano. Es con el saxofón con el que curso en el <b>Conservatorio de Cervera</b>.</p>
                            <p>Junto con mis estudios de música también me gradué en <b>Administración y Dirección de Empresas 📈</b> por la Universidad de Lleida y en Centre College, Kentucky, <b>Estados Unidos 🇺🇸</b>, donde estudié una mezcla de materias en enseñanza liberal que van desde el Jazz y la música tradicional hasta las finanzas y la economía.</p>
                            <p>En 2013 regreso <b>de Estados Unidos a España</b>, es un tiempo de readaptación, donde me incorporo como saxofonista en bandas de funk-disco, de rockabilly y de jazz, siempre inquieto por tocar y aprender de los distintos estilos, y buscando la manera de presentar los proyectos en conciertos y eventos. En este tiempo sigo formándome también como músico en academias.</p>
                            <p>Ya en 2015 me mudo a <b>Puerto Rico 🇵🇷</b>, estableciéndome en su capital, San Juan. Es allí donde empiezo a familiarizarme con toda la música tradicional del acrhipiélago, especialmente la Salsa, Bomba, Rumba y Plena. En Puerto Rico formé mi agrupación con músicos del <b>Conservatorio de Música de Puerto Rico</b>, actuando en lugares tan icónicos como el escenario del barrio de La Perla, en el Viejo San Juan, el mismo escenario donde actuó la mítica banda Puertorriqueña Calle 13 tras ser galardonados con premios Grammy Latino.</p>
                            <p>Al regreso de Puerto Rico, y tras un breve letargo en <b>Argentina 🇦🇷</b>, me instalé de nuevo en la península y nació <b>SAXONARA</b>, mi mayor proyecto hasta el momento y al que le dedico todo mi tiempo y energía.</p>
